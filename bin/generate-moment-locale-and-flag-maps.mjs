#!/usr/bin/env node

/**
 * Writes the explicit import maps for moment locales and flag SVGs, so that
 * neither needs a template-literal import, which only webpack can bundle.
 *
 * Run it again after upgrading `moment` or `flag-icons`. The maps' unit tests
 * fail when they don't match the installed packages.
 */

import { readdirSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { format, resolveConfig } from 'prettier';

const repoRoot = path.resolve( path.dirname( fileURLToPath( import.meta.url ) ), '..' );
const clientRequire = createRequire( path.join( repoRoot, 'client/package.json' ) );

const HEADER =
	'// This file is generated by bin/generate-moment-locale-and-flag-maps.mjs. Do not edit it by hand.\n\n';

function listFiles( packageName, subdirectory, extension ) {
	const packageDir = path.dirname( clientRequire.resolve( `${ packageName }/package.json` ) );
	return readdirSync( path.join( packageDir, subdirectory ) )
		.filter( ( file ) => file.endsWith( extension ) )
		.map( ( file ) => file.slice( 0, -extension.length ) )
		.sort();
}

async function writeFormatted( relativePath, source ) {
	const target = path.join( repoRoot, relativePath );
	const options = await resolveConfig( target );
	writeFileSync( target, await format( source, { ...options, filepath: target } ) );
}

const quoteKey = ( name ) => `'${ name }'`;

async function writeMomentLocaleLoaders() {
	const locales = listFiles( 'moment', 'locale', '.js' );
	const entries = locales.map(
		( locale ) =>
			`${ quoteKey( locale ) }: () => import( /* webpackChunkName: "moment-locale-${ locale }" */ 'moment/locale/${ locale }' ),`
	);
	await writeFormatted(
		'client/components/localized-moment/moment-locale-loaders.js',
		`${ HEADER }export default {\n${ entries.join( '\n' ) }\n};\n`
	);
	return locales.length;
}

async function writeFlagUrls() {
	const codes = listFiles( 'flag-icons', 'flags/4x3', '.svg' );
	// Codes such as `gb-eng` aren't identifiers, so they're exported under string names.
	const exportName = ( code ) => ( /^[a-z]+$/.test( code ) ? code : `'${ code }'` );
	const exports = codes.map(
		( code ) =>
			`export { default as ${ exportName( code ) } } from 'flag-icons/flags/4x3/${ code }.svg';`
	);
	await writeFormatted( 'client/lib/flags/flag-urls.js', `${ HEADER }${ exports.join( '\n' ) }\n` );
	return codes.length;
}

const localeCount = await writeMomentLocaleLoaders();
const flagCount = await writeFlagUrls();
console.log( `Wrote ${ localeCount } moment locale loaders and ${ flagCount } flag URLs.` );
