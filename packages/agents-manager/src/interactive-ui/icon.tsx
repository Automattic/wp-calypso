import { createComponentImplementation } from '@a2ui/react/v0_9';
import { DataBindingSchema, IconApi } from '@a2ui/web_core/v0_9';
import {
	Icon as WordPressIcon,
	plus,
	arrowLeft,
	arrowRight,
	calendar,
	check,
	close,
	trash,
	download,
	pencil,
	error,
	starFilled,
	starEmpty,
	help,
	home,
	info,
	lock,
	unlock,
	envelope,
	menu,
	moreVertical,
	moreHorizontal,
	bell,
	payment,
	people,
	image,
	search,
	send,
	settings,
	share,
	cart,
	upload,
	seen,
	unseen,
	caution,
} from '@wordpress/icons';
import { z } from 'zod';

const icons = {
	accountCircle: people,
	add: plus,
	arrowBack: arrowLeft,
	arrowForward: arrowRight,
	calendarToday: calendar,
	check,
	close,
	delete: trash,
	download,
	edit: pencil,
	event: calendar,
	error,
	favorite: starFilled,
	favoriteOff: starEmpty,
	help,
	home,
	info,
	lock,
	lockOpen: unlock,
	mail: envelope,
	menu,
	moreVert: moreVertical,
	moreHoriz: moreHorizontal,
	notifications: bell,
	payment,
	person: people,
	photo: image,
	search,
	send,
	settings,
	share,
	shoppingCart: cart,
	star: starFilled,
	starOff: starEmpty,
	upload,
	visibility: seen,
	visibilityOff: unseen,
	warning: caution,
};

export default createComponentImplementation(
	{
		name: IconApi.name,
		schema: IconApi.schema.pick( { name: true } ).extend( {
			name: z.union( [
				z.enum( Object.keys( icons ) as [ keyof typeof icons, ...Array< keyof typeof icons > ] ),
				DataBindingSchema,
			] ),
		} ),
	},
	( { props } ) => <WordPressIcon icon={ icons[ props.name ] } fill="currentColor" />
);
