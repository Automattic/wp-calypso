/**
 * Regenerates src/utils/tlds.ts from the IANA root zone database.
 *
 * Usage: node packages/onboarding/bin/update-tlds.mjs
 */
import { writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const SOURCE_URL = 'https://data.iana.org/TLD/tlds-alpha-by-domain.txt';
const OUTPUT_PATH = resolve( dirname( fileURLToPath( import.meta.url ) ), '../src/utils/tlds.ts' );

const response = await fetch( SOURCE_URL );
if ( ! response.ok ) {
	throw new Error( `Failed to fetch ${ SOURCE_URL }: ${ response.status }` );
}

const body = await response.text();
const lines = body.split( '\n' ).map( ( line ) => line.trim() );
const header = lines.find( ( line ) => line.startsWith( '#' ) ) ?? '';
const tlds = lines
	.filter( ( line ) => line && ! line.startsWith( '#' ) )
	.map( ( line ) => line.toLowerCase() )
	.sort();

const output = [
	'/**',
	' * Generated by bin/update-tlds.mjs. Do not edit by hand.',
	` * Source: ${ SOURCE_URL }`,
	` * ${ header.replace( /^#\s*/, '' ) }`,
	' */',
	'export const TLDS: ReadonlySet< string > = new Set( [',
	...tlds.map( ( tld ) => `\t'${ tld }',` ),
	'] );',
	'',
].join( '\n' );

await writeFile( OUTPUT_PATH, output );
console.log( `Wrote ${ tlds.length } TLDs to ${ OUTPUT_PATH }` );
